import hre from "hardhat";
import fs from "fs";
import path from "path";

// Writes typed ABI constants for the web app and the CRE workflow.
async function main() {
  const names = ["SpraycashPayroll", "FxRateReceiver", "SpraycashUSD", "SpraycashForwarder"];
  let src = "// Generated by contracts/scripts/export-abi.ts. Do not edit.\n\n";
  for (const name of names) {
    const { abi } = await hre.artifacts.readArtifact(name);
    const constName = name.charAt(0).toLowerCase() + name.slice(1) + "Abi";
    src += `export const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
  }
  const targets = [path.join(__dirname, "..", "..", "web", "src", "lib", "abi.ts")];
  for (const target of targets) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, src);
    console.log(`Wrote ${target}`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
